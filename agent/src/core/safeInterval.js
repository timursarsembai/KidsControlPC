// Периодическая задача, которая не наслаивается сама на себя и не роняет
// агента.
//
// Обычный setInterval с асинхронной задачей ведёт себя плохо ровно там, где
// это опаснее всего — на медленном компьютере ребёнка. Если проверка правил
// раз в пять секунд занимает семь, запуски начинают накладываться: каждый
// держит свои списки процессов, память растёт, компьютер тормозит ещё
// сильнее, проходы становятся ещё длиннее. Так нехватка памяти превращается
// в лавину.
//
// Второе: брошенная из такой задачи ошибка становится необработанным
// промисом, а это в Node 18 — смерть процесса. Служба его поднимет, но
// ребёнок на эти секунды остаётся без присмотра.

/**
 * @param {string} name       — для записи в журнал
 * @param {number} intervalMs — как часто запускать
 * @param {() => any} task    — сама задача, может быть асинхронной
 * @param {object} [options]
 * @param {number} [options.maxRunMs] — после какого времени считать предыдущий
 *   проход зависшим и всё же запустить новый
 * @param {(msg: string) => void} [options.log]
 */
export function safeInterval(name, intervalMs, task, { maxRunMs = 60_000, log = console.log } = {}) {
  let startedAt = 0
  let skipped = 0

  const timer = setInterval(async () => {
    if (startedAt) {
      const running = Date.now() - startedAt

      // Пропускать бесконечно нельзя: если проход завис навсегда (сетевой
      // вызов без таймаута, зависший системный запрос), блокировка означала
      // бы, что правила больше никогда не применяются. Лучше пустить второй
      // проход и записать это, чем молча перестать защищать ребёнка.
      if (running < maxRunMs) {
        skipped++
        // Один пропуск — обычное дело на загруженной машине, о нём молчим.
        if (skipped === 3 || skipped % 20 === 0) {
          log(`⏳ ${name}: предыдущий проход идёт ${Math.round(running / 1000)} с, пропущено подряд: ${skipped}`)
        }
        return
      }

      log(`⚠️ ${name}: проход идёт ${Math.round(running / 1000)} с — похоже, завис; запускаю новый`)
    }

    skipped = 0
    startedAt = Date.now()
    try {
      await task()
    } catch (err) {
      log(`⚠️ ${name}: ${err?.message || err}`)
    } finally {
      startedAt = 0
    }
  }, intervalMs)

  // Намеренно без unref(): таймер должен удерживать процесс живым. Служба
  // без активных дескрипторов завершилась бы сама, стоило пропасть сети.
  return timer
}
