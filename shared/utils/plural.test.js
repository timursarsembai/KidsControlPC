import { describe, it, expect } from 'vitest'
import { plural, withCount } from './plural.js'

describe('склонение при числе', () => {
  it('единственное только на настоящей единице', () => {
    expect(plural(1, 'устройство', 'устройства', 'устройств')).toBe('устройство')
    expect(plural(21, 'устройство', 'устройства', 'устройств')).toBe('устройство')
    expect(plural(101, 'устройство', 'устройства', 'устройств')).toBe('устройство')
  })

  it('двойственное на 2–4', () => {
    for (const n of [2, 3, 4, 22, 33, 104]) {
      expect(plural(n, 'устройство', 'устройства', 'устройств')).toBe('устройства')
    }
  })

  // Ровно то, на чём ломается наивное правило «меньше пяти — устройства».
  it('множественное на 11–14, а не двойственное', () => {
    for (const n of [11, 12, 13, 14, 111, 112]) {
      expect(plural(n, 'устройство', 'устройства', 'устройств')).toBe('устройств')
    }
  })

  it('множественное на 0, 5–20 и круглых', () => {
    for (const n of [0, 5, 9, 10, 15, 20, 100]) {
      expect(plural(n, 'устройство', 'устройства', 'устройств')).toBe('устройств')
    }
  })

  it('подставляет число', () => {
    expect(withCount(1, 'устройство', 'устройства', 'устройств')).toBe('1 устройство')
    expect(withCount(11, 'устройство', 'устройства', 'устройств')).toBe('11 устройств')
  })
})
