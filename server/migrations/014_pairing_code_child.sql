-- Какому ребёнку достанется устройство, привязанное этим кодом.
--
-- Родитель нажимает «добавить устройство» внутри профиля, а привязка
-- происходит через несколько минут, на другом компьютере. Без этого поля
-- связь теряется по дороге, и новое устройство всякий раз оказывается «без
-- профиля» — родителю остаётся переносить его вручную и гадать, какое из
-- двух только что появившихся чьё.
--
-- Профиль могут удалить, пока код ещё живёт: тогда устройство привяжется без
-- профиля, а не потеряет возможность привязаться вовсе.

alter table pairing_codes
  add column child_id uuid references children (id) on delete set null;
